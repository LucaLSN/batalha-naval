import random

class Tabuleiro():
  def __init__(self, layout):
    self.layout = layout
    self.grade = []

    for i in range(self.layout):
      self.grade.append(self.layout * ['~'])

  def posicionar_navio(self, linha, coluna, tamanho_navio, direcao):
      if direcao == 'H':
          if coluna + tamanho_navio > self.layout:
              print('Posição inválida')
              return

          for i in range(tamanho_navio):
              if self.grade[linha][coluna + i] != "~":
                  print('Posição preenchida')
                  return

          for i in range(tamanho_navio):
            self.grade[linha][coluna + i] = 'N'

      elif direcao == 'V':
          if linha + tamanho_navio > self.layout:
              print('Posição inválida')
              return

          for i in range(tamanho_navio):
              if self.grade[linha + i][coluna] != "~":
                  print('Posição preenchida')
                  return

          for i in range(tamanho_navio):
            self.grade[linha + i][coluna] = 'N'

  def receber_tiro(self, linha, coluna):
      if self.grade[linha][coluna] == '~':
        self.grade[linha][coluna] = 'O'
        print('\nAtirou na água!')

      elif self.grade[linha][coluna] == 'N':
        self.grade[linha][coluna] = 'X'
        print('\nAcertou um navio!')
      else:
        print('Você já atirou nesta posição!')


  def exibir_tabuleiro(self, ocultar_navios = True):
    print("\n======{ BATALHA NAVAL }======\n")
    print('  A B C D E F')
    for i, item in enumerate(self.grade):
      numero_linha = i + 1

      if ocultar_navios == True:
            grade_itens = ' '.join(item).replace('N', '~')
      else:
            grade_itens = ' '.join(item)

      print(f'{numero_linha} {grade_itens}')


class Partida():
  def __init__(self):
    self.tabuleiro_jogador = Tabuleiro(6)

  def jogar(self):
    partida = 0

    posicao_linha = random.randint(0,5)
    posicao_coluna = random.randint(0,5)
    tamanho_navio_navio  = 2
    orientacao_lista = ["H", "V"]
    orientacao = random.choice(orientacao_lista)

    self.tabuleiro_jogador.posicionar_navio(posicao_linha, posicao_coluna, tamanho_navio_navio, orientacao)

    while partida != 3:

      self.tabuleiro_jogador.exibir_tabuleiro()

      escolher_linha = int(input('Digite uma LINHA (1-6) para o tiro: '))
      escolher_coluna = str(input('Digite uma COLUNA (A-F) para o tiro: '))

      linha_convertida = escolher_linha - 1

      mapa_colunas = {'A': 0, 'B': 1, 'C': 2, 'D': 3, 'E': 4, 'F': 5}
      coluna_convertida = mapa_colunas[escolher_coluna.upper()]

      self.tabuleiro_jogador.receber_tiro(linha_convertida, coluna_convertida)

      partida += 1
      print(f'RESTAM {abs(partida - 3)} TENTATIVAS')

    print("\n===GAME OVER!===")
    self.tabuleiro_jogador.exibir_tabuleiro(ocultar_navios = False)

partida = Partida()
partida.jogar()

